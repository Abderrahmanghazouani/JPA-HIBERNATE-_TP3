package com.example.model;

import javax.persistence.*;
import java.util.HashSet;
import java.util.Set;

@Entity
public class Salle {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false, unique = true)
    private String nom;

    private int capacite;

    // Une salle a plusieurs reservations (cote inverse, lecture seule).
    // Pas de cascade ici : c'est l'Utilisateur qui "possede" le cycle de vie
    // des reservations ; deux proprietaires creeraient des conflits a la suppression.
    @OneToMany(mappedBy = "salle")
    private Set<Reservation> reservations = new HashSet<>();

    // Cote proprietaire du ManyToMany : il definit la table de jointure.
    // Pas de REMOVE : un equipement partage ne doit pas etre supprime avec la salle.
    @ManyToMany(cascade = {CascadeType.PERSIST, CascadeType.MERGE})
    @JoinTable(
            name = "salle_equipement",
            joinColumns = @JoinColumn(name = "salle_id"),
            inverseJoinColumns = @JoinColumn(name = "equipement_id")
    )
    private Set<Equipement> equipements = new HashSet<>();

    public Salle() {
    }

    public Salle(String nom, int capacite) {
        this.nom = nom;
        this.capacite = capacite;
    }

    public void addEquipement(Equipement equipement) {
        equipements.add(equipement);
        equipement.getSalles().add(this);
    }

    public void removeEquipement(Equipement equipement) {
        equipements.remove(equipement);
        equipement.getSalles().remove(this);
    }

    public Long getId() { return id; }
    public String getNom() { return nom; }
    public void setNom(String nom) { this.nom = nom; }
    public int getCapacite() { return capacite; }
    public void setCapacite(int capacite) { this.capacite = capacite; }
    public Set<Reservation> getReservations() { return reservations; }
    public Set<Equipement> getEquipements() { return equipements; }

    @Override
    public String toString() {
        return "Salle{id=" + id + ", nom='" + nom + "', capacite=" + capacite + "}";
    }
}
